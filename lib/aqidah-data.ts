export function getAqidahBook(id: number): AqidahBook | undefined {
  return AQIDAH_BOOKS.find((book) => book.id === id);
}

export function getAqidahLesson(
  bookId: number,
  lessonId: number,
): { book: AqidahBook; lesson: AqidahLesson } | undefined {
  const book = getAqidahBook(bookId);
  const lesson = book?.lessons.find((l) => l.id === lessonId);

  if (!book || !lesson) return undefined;

  return { book, lesson };
}
